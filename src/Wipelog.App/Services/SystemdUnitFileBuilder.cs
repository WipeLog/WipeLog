using System.Text;
using Wipelog.Core.Preferences;

namespace Wipelog.App.Services;

internal static class SystemdUnitFileBuilder
{
    /// <summary>
    /// Render the contents of <c>wipelog.service</c> from the supplied
    /// daemon config. Paths are quoted; the file ends with a trailing newline.
    /// </summary>
    public static string Build(DaemonConfig config)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Wipelog GUI. Edits made here will be");
        sb.AppendLine("# overwritten on the next install/reinstall.");
        sb.AppendLine("[Unit]");
        sb.AppendLine("Description=Wipelog daemon");
        sb.AppendLine("After=graphical-session.target");
        sb.AppendLine("PartOf=graphical-session.target");
        sb.AppendLine();
        sb.AppendLine("[Service]");
        sb.AppendLine("Type=simple");
        sb.Append("ExecStart=");
        sb.Append(Quote(config.DaemonExecutablePath));
        AppendOption(sb, "--log-dir", config.LogDirectory);
        AppendOption(sb, "--log-pattern", config.LogPattern);
        AppendOption(sb, "--output", config.OutputDirectory);
        if (!string.IsNullOrWhiteSpace(config.DatabasePath))
        {
            AppendOption(sb, "--db-path", config.DatabasePath);
        }
        AppendOption(sb, "--executable", config.GpuScreenRecorderExecutable);
        AppendOption(sb, "--window", config.CaptureTarget);
        AppendOption(sb, "--framerate", config.Framerate.ToString(System.Globalization.CultureInfo.InvariantCulture));
        AppendOption(sb, "--codec", config.Codec);
        AppendOption(sb, "--container", config.Container);
        // One --audio per track so the daemon's argv parser sees them as
        // distinct entries (it collapses to one if you concat them).
        var tracks = config.AudioTracks.Count > 0
            ? config.AudioTracks
            : new[] { "default_output" };
        foreach (var track in tracks)
        {
            AppendOption(sb, "--audio", track);
        }
        AppendOption(sb, "--video-quality", config.VideoQuality);
        if (!string.IsNullOrWhiteSpace(config.VideoResolution) &&
            !string.Equals(config.VideoResolution, VideoResolutions.Source, StringComparison.OrdinalIgnoreCase))
        {
            AppendOption(sb, "--video-resolution", config.VideoResolution);
        }
        if (config.PreRollSeconds is { } preroll)
        {
            AppendOption(sb, "--preroll-seconds",
                preroll.ToString(System.Globalization.CultureInfo.InvariantCulture));
        }
        if (config.PostRollSeconds is { } postroll && postroll > 0)
        {
            AppendOption(sb, "--postroll-seconds",
                postroll.ToString(System.Globalization.CultureInfo.InvariantCulture));
        }
        sb.AppendLine();
        sb.AppendLine("Restart=on-failure");
        sb.AppendLine("RestartSec=5s");
        sb.AppendLine("StandardOutput=journal");
        sb.AppendLine("StandardError=journal");
        sb.AppendLine();
        sb.AppendLine("[Install]");
        sb.AppendLine("WantedBy=graphical-session.target");
        return sb.ToString();
    }

    private static void AppendOption(StringBuilder sb, string flag, string value)
    {
        // ExecStart with continuation: backslash + newline + indent. systemd
        // accepts this style and journalctl/status renders it cleanly.
        sb.Append(" \\");
        sb.AppendLine();
        sb.Append("    ");
        sb.Append(flag);
        sb.Append(' ');
        sb.Append(Quote(value));
    }

    /// <summary>
    /// Quote a value for systemd's ExecStart parser. Paths containing spaces
    /// (e.g. "Program Files (x86)" in a typical Wine prefix) need quoting;
    /// quotes inside the value get escaped as <c>\"</c>.
    /// </summary>
    internal static string Quote(string value)
    {
        if (value is null) return "\"\"";
        // systemd's escaping: backslash escapes the next character in quoted strings.
        var escaped = value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        return $"\"{escaped}\"";
    }
}
